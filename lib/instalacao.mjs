import * as arquivos from 'node:fs/promises';
import * as caminhos from 'node:path';
import { comTrava, gravar, gravarJson, lerJson, lerOpcional, listar, resolverSeguro, resumo, serializar } from './arquivos.mjs';

const INICIO = '<!-- equipe-pedro:inicio -->';
const FIM = '<!-- equipe-pedro:fim -->';
const NEGACOES_CLAUDE = ['Bash(git *)', 'Bash(gh *)'];

function blocoEntrada() {
  return `${INICIO}\nRead and follow [the portable team entry instructions](.equipe/base/entrada.md). Git and GitHub operations require Pedro's explicit authorization for the exact operation.\n${FIM}`;
}

function extrairBloco(texto) {
  const inicio = texto.indexOf(INICIO), fim = texto.indexOf(FIM);
  if (inicio === -1 || fim === -1) return null;
  return texto.slice(inicio, fim + FIM.length);
}

function substituirBloco(texto, bloco) {
  const inicio = texto.indexOf(INICIO), fim = texto.indexOf(FIM);
  if ((inicio === -1) !== (fim === -1)) throw new Error('Marcadores gerenciados incompletos no arquivo de entrada.');
  if (inicio === -1) return `${texto.trimEnd()}${texto.trim() ? '\n\n' : ''}${bloco}\n`;
  return texto.slice(0, inicio) + bloco + texto.slice(fim + FIM.length);
}

function removerBloco(texto) {
  const inicio = texto.indexOf(INICIO), fim = texto.indexOf(FIM);
  if (inicio === -1 && fim === -1) return texto;
  if (inicio === -1 || fim === -1) throw new Error('Marcadores gerenciados incompletos no arquivo de entrada.');
  return (texto.slice(0, inicio) + texto.slice(fim + FIM.length)).replace(/^\s+|\s+$/g, '') + '\n';
}

function escaparToml(texto) { return JSON.stringify(texto); }

async function artefatosDaFonte(origem) {
  const artefatos = new Map();
  for (const relativo of await listar(caminhos.join(origem, 'base'))) {
    const conteudo = await arquivos.readFile(caminhos.join(origem, 'base', ...relativo.split('/')));
    artefatos.set(`.equipe/base/${relativo}`, conteudo);
  }
  for (const relativo of ['equipe.mjs', 'package.json', 'versao.json']) {
    artefatos.set(`.equipe/runtime/${relativo}`, await arquivos.readFile(caminhos.join(origem, relativo)));
  }
  for (const relativo of await listar(caminhos.join(origem, 'lib'))) {
    artefatos.set(`.equipe/runtime/lib/${relativo}`, await arquivos.readFile(caminhos.join(origem, 'lib', ...relativo.split('/'))));
  }
  artefatos.set('.equipe/configuracao.exemplo.json', await arquivos.readFile(caminhos.join(origem, 'configuracao.exemplo.json')));
  const papeis = await lerJson(caminhos.join(origem, 'base', 'papeis.json'));
  for (const papel of papeis.filter(item => item.identificador !== 'coordinator')) {
    const instrucoes = await arquivos.readFile(caminhos.join(origem, 'base', 'papeis', `${papel.identificador}.md`), 'utf8');
    const toml = `name = ${escaparToml(papel.identificador)}\ndescription = ${escaparToml(papel.descricao)}\ndeveloper_instructions = ${escaparToml(instrucoes)}\n`;
    artefatos.set(`.codex/agents/${papel.identificador}.toml`, Buffer.from(toml));
    const claude = `---\nname: ${papel.identificador}\ndescription: ${JSON.stringify(papel.descricao)}\n---\n\n${instrucoes}`;
    artefatos.set(`.claude/agents/${papel.identificador}.md`, Buffer.from(claude));
  }
  for (const relativo of await listar(caminhos.join(origem, 'base', 'skills'))) {
    if (!relativo.endsWith('/SKILL.md')) continue;
    const conteudo = await arquivos.readFile(caminhos.join(origem, 'base', 'skills', ...relativo.split('/')));
    artefatos.set(`.agents/skills/${relativo}`, conteudo);
    artefatos.set(`.claude/skills/${relativo}`, conteudo);
  }
  const regras = `# Generated by equipe-pedro. Pedro retains Git/GitHub control.\nprefix_rule(pattern=["git"], decision="forbidden", justification="Git operations require Pedro's explicit authorization for the exact operation.")\nprefix_rule(pattern=["gh"], decision="forbidden", justification="GitHub operations require Pedro's explicit authorization for the exact operation.")\n`;
  artefatos.set('.codex/rules/equipe-pedro.rules', Buffer.from(regras));
  return artefatos;
}

async function prepararEntradas(projeto, artefatos) {
  const bloco = blocoEntrada();
  for (const relativo of ['AGENTS.md', 'CLAUDE.md']) {
    const atual = await lerOpcional(await resolverSeguro(projeto, relativo));
    artefatos.set(relativo, Buffer.from(substituirBloco(atual?.toString('utf8') ?? '', bloco)));
  }
}

async function mesclarClaude(projeto) {
  const caminho = await resolverSeguro(projeto, '.claude/settings.json');
  const atual = await lerOpcional(caminho);
  const configuracao = atual ? JSON.parse(atual.toString('utf8')) : {};
  configuracao.permissions ??= {};
  configuracao.permissions.deny ??= [];
  const adicionadas = NEGACOES_CLAUDE.filter(item => !configuracao.permissions.deny.includes(item));
  configuracao.permissions.deny.push(...adicionadas);
  await gravarJson(caminho, configuracao);
  return adicionadas;
}

async function removerNegacoesClaude(projeto, adicionadas) {
  if (!adicionadas?.length) return;
  const caminho = await resolverSeguro(projeto, '.claude/settings.json');
  const atual = await lerOpcional(caminho);
  if (!atual) return;
  const configuracao = JSON.parse(atual.toString('utf8'));
  if (Array.isArray(configuracao.permissions?.deny)) configuracao.permissions.deny = configuracao.permissions.deny.filter(item => !adicionadas.includes(item));
  await gravarJson(caminho, configuracao);
}

async function manifestoAtual(projeto) {
  const conteudo = await lerOpcional(await resolverSeguro(projeto, '.equipe/manifesto.json'));
  return conteudo ? JSON.parse(conteudo.toString('utf8')) : null;
}

async function verificarAlteracoes(projeto, manifesto) {
  const conflitos = [];
  for (const item of manifesto?.arquivosGerenciados ?? []) {
    const atual = await lerOpcional(await resolverSeguro(projeto, item.caminho));
    if (!atual) { conflitos.push(item.caminho); continue; }
    const observado = item.modo === 'bloco' ? extrairBloco(atual.toString('utf8')) : atual;
    if (observado === null || resumo(observado) !== item.resumo) conflitos.push(item.caminho);
  }
  return conflitos;
}

async function guardarVersao(projeto, manifesto) {
  if (!manifesto) return;
  for (const item of manifesto.arquivosGerenciados) {
    const atual = await lerOpcional(await resolverSeguro(projeto, item.caminho));
    if (atual) await gravar(await resolverSeguro(projeto, `.equipe/versoes/${manifesto.versao}/${item.caminho}`), atual);
  }
  await gravarJson(await resolverSeguro(projeto, `.equipe/versoes/${manifesto.versao}/manifesto.json`), manifesto);
}

async function verificarColisoes(projeto, artefatos, anterior) {
  const gerenciados = new Set((anterior?.arquivosGerenciados ?? []).map(item => item.caminho));
  const colisoes = [];
  for (const [relativo] of artefatos) {
    if (gerenciados.has(relativo) || ['AGENTS.md', 'CLAUDE.md'].includes(relativo)) continue;
    if (await lerOpcional(await resolverSeguro(projeto, relativo))) colisoes.push(relativo);
  }
  return colisoes;
}

async function reconciliarObsoletos(projeto, anterior, proximos) {
  const proximosCaminhos = new Set([...proximos.keys()]); const preservados = [];
  for (const item of anterior?.arquivosGerenciados ?? []) {
    if (proximosCaminhos.has(item.caminho) || ['AGENTS.md', 'CLAUDE.md'].includes(item.caminho)) continue;
    const destino = await resolverSeguro(projeto, item.caminho), atual = await lerOpcional(destino);
    if (!atual) continue;
    if (resumo(atual) !== item.resumo) { preservados.push(item.caminho); continue; }
    await arquivos.rm(destino, { force: true });
  }
  return preservados;
}

export async function instalar({ projeto, origem, atualizar = false, previa = false }) {
  return comTrava(projeto, async () => {
    const anterior = await manifestoAtual(projeto);
    const artefatos = await artefatosDaFonte(origem);
    await prepararEntradas(projeto, artefatos);
    const colisoes = await verificarColisoes(projeto, artefatos, anterior);
    if (colisoes.length) return { estado: 'colisao', colisoes, previa: true };
    if (previa) return { estado: 'previa', totalArquivos: artefatos.size, versao: (await lerJson(caminhos.join(origem, 'versao.json'))).versao };
    if (anterior) {
      const conflitos = await verificarAlteracoes(projeto, anterior);
      if (conflitos.length) return { estado: 'conflito', conflitos };
      if (!atualizar && anterior.versao === (await lerJson(caminhos.join(origem, 'versao.json'))).versao) return { estado: 'inalterado', versao: anterior.versao };
      await guardarVersao(projeto, anterior);
    }
    const obsoletosPreservados = await reconciliarObsoletos(projeto, anterior, artefatos);
    for (const [relativo, conteudo] of artefatos) await gravar(await resolverSeguro(projeto, relativo), conteudo);
    const adicionadas = anterior?.configuracoesMescladas?.claude ?? await mesclarClaude(projeto);
    const versao = (await lerJson(caminhos.join(origem, 'versao.json'))).versao;
    const manifesto = { versao, instaladoEm: new Date().toISOString(), arquivosGerenciados: [...artefatos].map(([caminho, conteudo]) => {
      if (['AGENTS.md', 'CLAUDE.md'].includes(caminho)) return { caminho, modo: 'bloco', resumo: resumo(extrairBloco(conteudo.toString('utf8'))) };
      return { caminho, modo: 'arquivo', resumo: resumo(conteudo) };
    }), configuracoesMescladas: { claude: adicionadas } };
    await gravarJson(await resolverSeguro(projeto, '.equipe/manifesto.json'), manifesto);
    return { estado: anterior ? 'atualizado' : 'instalado', versao, totalArquivos: artefatos.size, obsoletosPreservados };
  });
}

export async function remover({ projeto }) {
  return comTrava(projeto, async () => {
    const manifesto = await manifestoAtual(projeto);
    if (!manifesto) return { estado: 'ausente' };
    const conflitos = await verificarAlteracoes(projeto, manifesto);
    if (conflitos.length) return { estado: 'conflito', conflitos };
    for (const item of manifesto.arquivosGerenciados) {
      if (['AGENTS.md', 'CLAUDE.md'].includes(item.caminho)) {
        const atual = await arquivos.readFile(await resolverSeguro(projeto, item.caminho), 'utf8');
        await gravar(await resolverSeguro(projeto, item.caminho), removerBloco(atual));
      } else await arquivos.rm(await resolverSeguro(projeto, item.caminho), { force: true });
    }
    await removerNegacoesClaude(projeto, manifesto.configuracoesMescladas?.claude);
    await arquivos.rm(await resolverSeguro(projeto, '.equipe/manifesto.json'), { force: true });
    return { estado: 'removido', totalArquivos: manifesto.arquivosGerenciados.length };
  });
}

export async function restaurar({ projeto, versao }) {
  return comTrava(projeto, async () => {
    const atual = await manifestoAtual(projeto);
    if (!atual) throw new Error('Não há instalação ativa para restaurar.');
    const conflitos = await verificarAlteracoes(projeto, atual);
    if (conflitos.length) return { estado: 'conflito', conflitos };
    const pasta = await resolverSeguro(projeto, `.equipe/versoes/${versao}`);
    const antigo = await lerJson(caminhos.join(pasta, 'manifesto.json'));
    const destinosAntigos = new Set(antigo.arquivosGerenciados.map(item => item.caminho));
    const preservados = [];
    for (const item of atual.arquivosGerenciados) {
      if (destinosAntigos.has(item.caminho) || ['AGENTS.md', 'CLAUDE.md'].includes(item.caminho)) continue;
      const destino = await resolverSeguro(projeto, item.caminho), conteudo = await lerOpcional(destino);
      if (!conteudo) continue;
      if (resumo(conteudo) !== item.resumo) preservados.push(item.caminho); else await arquivos.rm(destino, { force: true });
    }
    for (const item of antigo.arquivosGerenciados) {
      const conteudo = await arquivos.readFile(caminhos.join(pasta, ...item.caminho.split('/')));
      if (item.modo === 'bloco') {
        const destino = await resolverSeguro(projeto, item.caminho);
        const corrente = await arquivos.readFile(destino, 'utf8');
        await gravar(destino, substituirBloco(corrente, extrairBloco(conteudo.toString('utf8'))));
      } else await gravar(await resolverSeguro(projeto, item.caminho), conteudo);
    }
    await gravarJson(await resolverSeguro(projeto, '.equipe/manifesto.json'), antigo);
    return { estado: 'restaurado', versao, obsoletosPreservados: preservados };
  });
}

export async function diagnosticar(projeto) {
  const manifesto = await manifestoAtual(projeto);
  if (!manifesto) return { instalado: false };
  const conflitos = await verificarAlteracoes(projeto, manifesto);
  return { instalado: true, versao: manifesto.versao, arquivosGerenciados: manifesto.arquivosGerenciados.length, alteracoesLocais: conflitos };
}
